"""Generate every LaTeX table in the paper from result artifacts (booktabs).

No number is typed by hand: each cell is pulled from a JSON via mer_style and
formatted here, so a re-run of the sweep regenerates the tables verbatim and the
verify_shipped gate can re-derive every printed value.

Tables:
  I   main results   -> tab_main.tex
  II  prompting ablation (paired) -> tab_ablation.tex
  III Coco fragility census -> tab_coco.tex

Run:  python make_tables.py
"""
from __future__ import annotations

import os

import mer_style as S

HERE = os.path.dirname(os.path.abspath(__file__))


def _f(x: float, n: int = 3) -> str:
    return f"{x:.{n}f}"


def shipped_mean_error_f1(system: str) -> float:
    sh = S._load(os.path.join(S.GIL, f"{S._STEM[system]}_shipped.json"))
    return sh["shipped_50ms"]["_mean_error_f1"]


# --------------------------------------------------------------------------- #
def table_main() -> str:
    rows = []
    hms = []
    bands = {}
    for sysname in S.SYSTEMS:
        sw = S.sweep(sysname)
        i50 = sw["tau_ms"].index(50)
        hm, hm_lo, hm_hi = sw["hm"][i50], sw["hm_lo"][i50], sw["hm_hi"][i50]
        loc, loc_lo, loc_hi = sw["loc"][i50], sw["loc_lo"][i50], sw["loc_hi"][i50]
        _, band_hi, _, _ = S.bridge_band(sysname)
        hms.append(hm)
        bands[sysname] = band_hi
        sf = shipped_mean_error_f1(sysname)
        rows.append(
            f"{S.LABEL[sysname]} & {_f(sf)} & "
            f"{_f(hm)}~[{_f(hm_lo)},\\,{_f(hm_hi)}] & "
            f"{_f(loc)}~[{_f(loc_lo)},\\,{_f(loc_hi)}] & "
            f"$[0,\\,{_f(band_hi,2)}]$ \\\\")
    body = "\n".join(rows)
    # spread and ratio computed from the artifacts so the caption cannot go
    # stale when configurations change (reviewer finding, 2026-07-21)
    spread = max(hms) - min(hms)
    ratio = bands["polytune"] / spread
    ratio_word = {2: "twice", 3: "three times", 4: "four times"}.get(
        int(ratio), f"{ratio:.1f} times")
    return f"""% AUTO-GENERATED by figs/make_tables.py -- do not edit by hand.
\\begin{{table*}}[!t]
\\centering
\\caption{{MAESTRO test split, $\\tau=50$\\,ms, collapse radius $\\epsilon=50$\\,ms.
Corpus-pooled hidden mass $\\mathrm{{HM}}$ and localization $F$ with per-piece
bootstrap 95\\% intervals ($10^3$ resamples, $n=177$). \\emph{{Shipped}} is the
mean of the per-class missed/extra $F_1$ the systems' own protocols report. The
final column is the $\\mathrm{{HM}}$ band admitted by each system's shipped
counts alone (Prop.~\\ref{{prop:bridge}}); Polytune's is more than
{ratio_word} the ${spread:.2f}$ spread separating the three configurations.}}
\\label{{tab:main}}
\\begin{{tabular}}{{@{{}}l c c c c@{{}}}}
\\toprule
System & Shipped & $\\mathrm{{HM}}\\!\\downarrow$ & $F\\!\\uparrow$ & Admissible $\\mathrm{{HM}}$ \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table*}}
"""


def table_ablation() -> str:
    a = S.ablation()
    def line(metric):
        m = a[metric]
        lo, hi = m["paired_bootstrap_ci95"]
        p = m["wilcoxon_p"]
        p_s = "<10^{-12}" if p < 1e-12 else f"{p:.1e}".replace("e", "\\!\\times\\!10^{") + "}"
        name = "$\\mathrm{HM}$" if metric == "hm" else "$F$"
        return (f"{name} & {_f(m['mean_a'])} & {_f(m['mean_b'])} & "
                f"{m['mean_diff']:+.3f}~[{lo:+.3f},\\,{hi:+.3f}] & "
                f"${p_s}$ & {_f(m['cliffs_delta'],2)} \\\\")
    body = line("hm") + "\n" + line("loc_f1")
    return f"""% AUTO-GENERATED by figs/make_tables.py -- do not edit by hand.
\\begin{{table}}[!t]
\\centering
\\caption{{Effect of score conditioning on LadderSym, per-piece paired over the
$n={S.ablation()['n_used']}$ MAESTRO pieces ($\\tau=50$\\,ms). Means are
per-piece; the paired difference (prompted$-$unprompted) carries a $10^4$-resample
bootstrap interval; $p$ is a two-sided Wilcoxon signed-rank test and $\\delta$ is
Cliff's delta. Conditioning improves localization ($F$) with a medium effect
and reduces $\\mathrm{{HM}}$ with a small one.}}
\\label{{tab:ablation}}
\\footnotesize
\\begin{{tabular}}{{@{{}}l c c c c c@{{}}}}
\\toprule
 & prompt. & unpr. & $\\Delta$ [95\\% CI] & $p$ & $\\delta$ \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def table_coco() -> str:
    cen = S.coco_census()
    order = [("polytune", "Polytune"),
             ("laddersym_unprompted", "LadderSym"),
             ("laddersym_prompted", "LadderSym (pr.)")]
    rows = []
    for key, lab in order:
        c = cen[key]
        n = c["n_files"]
        h = {int(k): v for k, v in c["histogram"].items()}
        t1, t2, t3 = h.get(1, 0), h.get(2, 0), h.get(3, 0)
        under = c["n_offenders"]
        rows.append(f"{lab} & {n} & {100*t3/n:.1f} & {100*t2/n:.1f} & "
                    f"{100*t1/n:.1f} & {100*under/n:.1f} \\\\")
    body = "\n".join(rows)
    return f"""% AUTO-GENERATED by figs/make_tables.py -- do not edit by hand.
\\begin{{table}}[!t]
\\centering
\\caption{{CocoChorales, per-stem note-track census. The multi-instrument output
format encodes error class only by track position, so a stem is decoupled-scorable
only when all three class tracks are emitted (``3-track''). Every system drops
tracks on more than half of the $4284$ stems, leaving the surviving class
labels unrecoverable---the format cannot represent the errors the measure needs.}}
\\label{{tab:coco}}
\\small
\\begin{{tabular}}{{@{{}}l c c c c c@{{}}}}
\\toprule
System & Stems & 3-trk\\,\\% & 2-trk\\,\\% & 1-trk\\,\\% & under\\,\\% \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def table_null() -> str:
    """Supplementary Table S1: circular-shift null, from null_colo_*.json."""
    rows = []
    for sysname in S.SYSTEMS:
        d = S._load(os.path.join(
            S.GIL, f"null_colo_{S._STEM[sysname]}.json"))
        ot, nt = d["observed_matched_total"], d["null_matched_total"]["mean"]
        oo, no = d["observed_off_diagonal"], d["null_off_diagonal"]["mean"]
        rows.append(f"{S.LABEL[sysname]} & {ot}/{nt:.0f} & "
                    f"{d['enrichment_total']:.1f} & {oo}/{no:.0f} & "
                    f"{d['enrichment_off']:.1f} \\\\")
    body = "\n".join(rows)
    n_perm = S._load(os.path.join(
        S.GIL, f"null_colo_{S._STEM['polytune']}.json"))["n_perm"]
    return f"""% AUTO-GENERATED by figs/make_tables.py -- do not edit by hand.
\\begin{{table}}[!t]
\\centering
\\caption{{Circular-shift null, $\\tau=50$~ms, {n_perm} permutations.}}
\\label{{tab:snull}}
\\footnotesize
\\begin{{tabular}}{{@{{}}lcccc@{{}}}}
\\toprule
Configuration & \\multicolumn{{2}}{{c}}{{matched total}} & \\multicolumn{{2}}{{c}}{{off-diagonal}} \\\\
 & obs./null & $\\times$ & obs./null & $\\times$ \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def main() -> None:
    outdir = os.environ.get("MER_TABLE_OUTDIR", HERE)
    for name, fn in [(table_main(), "tab_main.tex"),
                     (table_ablation(), "tab_ablation.tex"),
                     (table_coco(), "tab_coco.tex"),
                     (table_null(), "tab_null.tex")]:
        dest = os.path.join(outdir, fn)
        with open(dest, "w", encoding="utf-8") as fh:
            fh.write(name)
        print("wrote", dest)


if __name__ == "__main__":
    main()
